// Regenerate packages/engine/src/fonts-catalog.ts from Google Fonts' public metadata.
// usage: curl -s https://fonts.google.com/metadata/fonts -o gf.json && node scripts/gen-font-catalog.cjs gf.json
const fs = require('fs');
const { join } = require('path');
const raw = fs.readFileSync(process.argv[2], 'utf8').replace(/^\)\]\}'\s*/, '');
const list = JSON.parse(raw).familyMetadataList;
const CAT = { 'Sans Serif': 'S', Serif: 'R', Display: 'D', Handwriting: 'H', Monospace: 'M' };
const rows = list
  .slice()
  .sort((a, b) => a.popularity - b.popularity)
  .map((f) => {
    const keys = Object.keys(f.fonts);
    const italic = keys.some((k) => k.endsWith('i'));
    const axis = f.axes.find((a) => a.tag === 'wght');
    const weights = axis ? `${axis.min}-${axis.max}` : keys.filter((k) => !k.endsWith('i')).join(',');
    return `${f.family}|${CAT[f.category] ?? 'S'}|${weights}${italic ? 'i' : ''}`;
  });
const out = `// Generated by scripts/gen-font-catalog.cjs: ${rows.length} Google Fonts families, most popular first.
// Line format: family|category (S sans, R serif, D display, H handwriting, M mono)|weights or min-max (variable)|i = has italics
export const GOOGLE_FONT_ROWS = ${JSON.stringify(rows.join('\n'))};
`;
fs.writeFileSync(join(__dirname, '../packages/engine/src/fonts-catalog.ts'), out);
console.log(rows.length, out.length);
