import { chromium } from 'playwright-core';
const [base, out] = process.argv.slice(2);
const b = await chromium.launch({ channel: 'msedge', headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
await p.goto(base + 'editor/'); await p.waitForSelector('.layer');
await p.locator('.layer', { hasText: 'Login' }).first().click();
await p.getByRole('tab', { name: 'Prototype' }).click();
await p.waitForTimeout(300);
await p.screenshot({ path: out });
console.log('start badge:', await p.locator('.start-badge').count(), 'tabs overflow:', await p.locator('.inspector .tabs').evaluate((el) => el.scrollWidth > el.clientWidth));
await b.close();
