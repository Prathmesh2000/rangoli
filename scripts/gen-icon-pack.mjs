// Regenerate packages/engine/src/icon-pack.ts from the Lucide icon set (ISC licence).
// usage: curl -s https://cdn.jsdelivr.net/npm/@iconify-json/lucide@1/icons.json -o lucide.json && node scripts/gen-icon-pack.mjs lucide.json
import { readFileSync, writeFileSync } from 'node:fs';
import { svgToIconSrc } from '../packages/engine/dist/icons-svg.js';

const data = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const size = data.width ?? 24;
const rows = [];
for (const [name, ic] of Object.entries(data.icons)) {
  try {
    const { src } = svgToIconSrc(`<svg viewBox="0 0 ${ic.width ?? size} ${ic.height ?? size}">${ic.body}</svg>`, 24);
    // the pack's stroke comes from the set, so per-shape widths of 2 and the marker line are dropped
    rows.push(`${name}|${src.split('\n').slice(1).map((l) => l.replace(/^path /, '').replace(/ w=2$/, '')).join(';')}`);
  } catch { /* nothing drawable */ }
}
const out = `// Generated by scripts/gen-icon-pack.mjs: ${rows.length} icons from Lucide (https://lucide.dev).
// ISC License. Copyright (c) for portions of Lucide are held by Cole Bemis 2013-2022 as part of Feather (MIT).
// All other copyright (c) for Lucide are held by Lucide Contributors 2022.
import { registerIconPack } from './icons.js';

registerIconPack('lucide', ${JSON.stringify(rows.join('\n'))});
`;
writeFileSync(new URL('../packages/engine/src/icon-pack.ts', import.meta.url), out);
console.log(rows.length, out.length);
