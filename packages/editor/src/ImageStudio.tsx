function CompPreview({ node }: { node: RNode }) {
  const version = useEditor((s) => s.version);
  const ref = useRef<HTMLDivElement>(null);
  useLayoutEffect(() => {
    const host = ref.current;
    const doc = getState().doc;
    if (!host || !doc) return;
    const only = cloneDocument(doc);
    only.page().children = [node.id];
    renderInto(host.shadowRoot ?? host.attachShadow({ mode: 'open' }), only, '.stage{padding:0}');
    const stage = host.shadowRoot!.querySelector<HTMLElement>('.stage');
    if (stage) {
      // fit to the available width with a transform (layout keeps its true size)
      const avail = Math.max(320, (host.parentElement?.parentElement?.clientWidth ?? 900) - 48);
      const w = stage.scrollWidth, h = stage.scrollHeight;
      const s = Math.min(1, avail / w);
      stage.style.transform = `scale(${s})`;
      stage.style.transformOrigin = '0 0';
      host.style.width = `${w * s}px`;
      host.style.height = `${h * s}px`;
    }
  }, [node.id, version]);
  return (
    <div className="img-preview">
      <div className="comp-host" ref={ref} />
      <p className="hint">{node.name} — exactly what will be exported.</p>
    </div>
  );
}

function CompPanel({ node }: { node: RNode }) {
  const [format, setFormat] = useState<ImageFormat>('png');
  const [scale, setScale] = useState(2);
  const url = useMemo(() => `/api/compose/${node.id}?format=${format}&scale=${scale}`, [node.id, format, scale]);
  return (
    <div className="props">
      <div className="inspector-head">
        <div className="inspector-title">{node.name}</div>
        <div className="inspector-sub">composition · #{node.id}</div>
      </div>
      <section className="section">
        <h3 className="section-title">Export</h3>
        <div className="row"><span className="row-label">Format</span><div className="row-control"><div className="seg">
          {(['png', 'webp', 'jpeg'] as const).map((f) => <button key={f} className="seg-item" role="radio" aria-checked={format === f} onClick={() => setFormat(f)}>{f.toUpperCase()}</button>)}
        </div></div></div>
        <div className="row"><span className="row-label">Scale</span><div className="row-control"><div className="seg">
          {[1, 2, 3].map((s) => <button key={s} className="seg-item" role="radio" aria-checked={scale === s} onClick={() => setScale(s)}>{s}×</button>)}
        </div></div></div>
        <div className="code-actions">
          <a className="btn" href={url} target="_blank" rel="noopener">Open image</a>
          <a className="btn" href={url} download={`${node.name}@${scale}x.${format}`}>Download</a>
          {canEdit() && <button className="btn btn-primary" onClick={() => void post<AssetMeta>(`/api/compose/${node.id}/save`, { format, scale }).then((m) => m && (setState({ imageSel: { kind: 'asset', id: m.id } }), toast('info', `Saved ${m.name}`)))}>Save as asset</button>}
        </div>
      </section>
      <section className="section">
        <h3 className="section-title">Edit</h3>
        <button className="btn" onClick={() => { setView('design'); select([node.id]); }}>Open in Design</button>
        <p className="hint" style={{ marginTop: 6 }}>Text, layout, colours and icons are live — change them in Design and export again.</p>
      </section>
    </div>
  );
}
